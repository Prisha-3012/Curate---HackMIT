const requirement = (
  id: string,
  label: string,
  group: string,
  optionIds: string[],
  recommendation: string,
  recommendationReason?: string,
): Need => ({
  id,
  label,
  group: { id: group.toLowerCase(), label: group },
  priority: "required",
  options: optionIds.map((optionId) => {
    const option = resources.find((resource) => resource.id === optionId);
    if (!option)
      throw new Error(`Missing Boston fixture resource: ${optionId}`);
    return option;
  }),
  recommendedOptionId: recommendation,
  recommendationReason,
});
